CREATE OR REPLACE FUNCTION public.create_pix_order(
  p_customer_name text,
  p_customer_email text,
  p_shipping_address jsonb,
  p_shipping_method text,
  p_shipping_cents integer,
  p_items jsonb
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_order_id uuid;
  v_item jsonb;
  v_product public.products%ROWTYPE;
  v_quantity integer;
  v_subtotal integer := 0;
  v_total integer;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  IF length(trim(coalesce(p_customer_name, ''))) < 2 THEN RAISE EXCEPTION 'Invalid customer name'; END IF;
  IF position('@' in coalesce(p_customer_email, '')) < 2 THEN RAISE EXCEPTION 'Invalid customer email'; END IF;
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN RAISE EXCEPTION 'Cart is empty'; END IF;
  IF p_shipping_cents IS NULL OR p_shipping_cents < 0 OR p_shipping_cents > 100000 THEN RAISE EXCEPTION 'Invalid shipping'; END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_quantity := (v_item ->> 'quantity')::integer;
    IF v_quantity IS NULL OR v_quantity < 1 OR v_quantity > 99 THEN RAISE EXCEPTION 'Invalid quantity'; END IF;
    SELECT * INTO v_product FROM public.products WHERE id = (v_item ->> 'product_id')::uuid AND active = true FOR UPDATE;
    IF NOT FOUND OR v_product.stock < v_quantity THEN RAISE EXCEPTION 'Product unavailable'; END IF;
    v_subtotal := v_subtotal + (v_product.price_cents * v_quantity);
  END LOOP;

  v_total := v_subtotal + p_shipping_cents;
  INSERT INTO public.orders (customer_user_id, customer_name, customer_email, status, payment_status, total_cents, shipping_address, shipping_method, shipping_cents)
  VALUES (auth.uid(), trim(p_customer_name), lower(trim(p_customer_email)), 'pending', 'pending', v_total, coalesce(p_shipping_address, '{}'::jsonb), coalesce(nullif(trim(p_shipping_method), ''), 'Entrega a combinar'), p_shipping_cents)
  RETURNING id INTO v_order_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_quantity := (v_item ->> 'quantity')::integer;
    SELECT * INTO v_product FROM public.products WHERE id = (v_item ->> 'product_id')::uuid;
    INSERT INTO public.order_items (order_id, product_id, product_name, unit_price_cents, quantity)
    VALUES (v_order_id, v_product.id, v_product.name, v_product.price_cents, v_quantity);
    UPDATE public.products SET stock = stock - v_quantity, updated_at = now() WHERE id = v_product.id;
  END LOOP;
  RETURN v_order_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.mark_pix_payment_informed(p_order_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.orders SET payment_status = 'informed', payment_informed_at = now(), updated_at = now()
  WHERE id = p_order_id AND customer_user_id = auth.uid() AND payment_status = 'pending' AND status <> 'cancelled';
  IF NOT FOUND THEN RAISE EXCEPTION 'Order unavailable'; END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_confirm_pix_payment(p_order_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_clarime_admin() THEN RAISE EXCEPTION 'Not authorized'; END IF;
  UPDATE public.orders SET payment_status = 'confirmed', status = CASE WHEN status = 'pending' THEN 'pending' ELSE status END, payment_confirmed_at = now(), updated_at = now()
  WHERE id = p_order_id AND payment_status IN ('pending', 'informed') AND status <> 'cancelled';
  IF NOT FOUND THEN RAISE EXCEPTION 'Order unavailable'; END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_update_order_progress(p_order_id uuid, p_status text, p_tracking_code text, p_cancelled_reason text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_clarime_admin() THEN RAISE EXCEPTION 'Not authorized'; END IF;
  IF p_status NOT IN ('pending', 'preparing', 'shipped', 'completed', 'cancelled') THEN RAISE EXCEPTION 'Invalid status'; END IF;
  UPDATE public.orders SET status = p_status, tracking_code = coalesce(p_tracking_code, ''), cancelled_reason = coalesce(p_cancelled_reason, ''), updated_at = now()
  WHERE id = p_order_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Order unavailable'; END IF;
END;
$$;

