/*
# Add manual Pix order flow for Clarimê

1. Modified tables
- `orders`: adds the authenticated customer owner, shipping address/method/value, payment notification and confirmation timestamps, cancellation reason, and tracking code.
- `order_items`: keeps the existing product snapshot and becomes readable by the order owner.
- `products`: active products can be viewed by signed-in customers; management writes remain administrator-only.

2. New tables
- `store_settings`: one protected row containing the official Pix key, holder, bank, and optional official QR image URL.

3. New secure functions
- `create_pix_order`: creates an order from server-side product prices and quantities, always starting with payment `pending`.
- `mark_pix_payment_informed`: lets only the order owner announce a transfer; it never confirms payment.
- `admin_confirm_pix_payment`: lets only the administrator confirm a payment.
- `admin_update_order_progress`: lets only the administrator change preparation/delivery status, tracking, or cancellation reason.

4. Security
- Customers can read only their own orders and order items.
- Only the administrator can change payment confirmation, fulfillment status, tracking, cancellation reason, and Pix settings.
- Direct client inserts and updates for orders and order items are removed; mutations use validated database functions.
- Totals are calculated from current product prices in the database, not from browser-submitted prices.

5. Important notes
- The existing rows and columns are preserved; only additive columns and compatible constraints are introduced.
- `payment_status = pending` means “Aguardando pagamento”; `informed` means “Pagamento informado”; `confirmed` means “Pago e confirmado”.
- The optional QR field stores only a URL to an official image configured by the administrator. No QR code is generated by the application.
*/

ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS customer_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS shipping_address jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS shipping_method text NOT NULL DEFAULT 'Entrega a combinar',
  ADD COLUMN IF NOT EXISTS shipping_cents integer NOT NULL DEFAULT 0 CHECK (shipping_cents >= 0),
  ADD COLUMN IF NOT EXISTS payment_informed_at timestamptz,
  ADD COLUMN IF NOT EXISTS payment_confirmed_at timestamptz,
  ADD COLUMN IF NOT EXISTS cancelled_reason text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS tracking_code text NOT NULL DEFAULT '';

ALTER TABLE public.orders DROP CONSTRAINT IF EXISTS orders_payment_status_check;
ALTER TABLE public.orders ADD CONSTRAINT orders_payment_status_check CHECK (payment_status IN ('pending', 'informed', 'confirmed', 'paid', 'refunded'));
ALTER TABLE public.orders DROP CONSTRAINT IF EXISTS orders_status_check;
ALTER TABLE public.orders ADD CONSTRAINT orders_status_check CHECK (status IN ('pending', 'paid', 'preparing', 'shipped', 'completed', 'cancelled'));

CREATE INDEX IF NOT EXISTS orders_customer_user_id_idx ON public.orders(customer_user_id);
CREATE INDEX IF NOT EXISTS orders_payment_status_idx ON public.orders(payment_status);

